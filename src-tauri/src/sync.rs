fn parse_clean_mod_name(filename: &str) -> String {
    let mut name = filename.strip_suffix(".jar").unwrap_or(filename);
    
    // Remove typical loaders & version suffixes
    let patterns = ["-neoforge", "-forge", "-fabric", "-quilt", "+mc", "_mc", "-mc", ".neoforge", ".forge", ".fabric"];
    for p in &patterns {
        if let Some(idx) = name.to_lowercase().find(p) {
            name = &name[..idx];
        }
    }

    // Strip numbers and version digits e.g. -1.21.1-1.0.0 or _1.21
    if let Some(dash_idx) = name.find('-') {
        let after = &name[dash_idx + 1..];
        if after.chars().next().map_or(false, |c| c.is_ascii_digit()) {
            name = &name[..dash_idx];
        }
    }
    if let Some(underscore_idx) = name.find('_') {
        let after = &name[underscore_idx + 1..];
        if after.chars().next().map_or(false, |c| c.is_ascii_digit()) {
            name = &name[..underscore_idx];
        }
    }

    let cleaned = name.replace(['_', '-'], " ");
    cleaned.split_whitespace()
        .map(|word| {
            let mut c = word.chars();
            match c.next() {
                None => String::new(),
                Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn scan_directory_for_items(dir: &Path, items: &mut Vec<String>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let p = entry.path();
            if p.is_dir() {
                scan_directory_for_items(&p, items);
            } else if p.is_file() {
                let file_name = p.file_name().unwrap_or_default().to_string_lossy().to_lowercase();
                
                // Parse JSON files (sqh_items.json, item.json, registries, etc.)
                if file_name.ends_with(".json") {
                    if let Ok(content) = fs::read_to_string(&p) {
                        if let Ok(json) = serde_json::from_str::<serde_json::Value>(&content) {
                            extract_items_from_json(&json, items);
                        }
                    }
                }
                // Parse SNBT files (FTB Quests)
                else if file_name.ends_with(".snbt") {
                    if let Ok(content) = fs::read_to_string(&p) {
                        for word in content.split(|c: char| c.is_whitespace() || c == '"' || c == '\'' || c == '{' || c == '}' || c == '[' || c == ']' || c == ',') {
                            let trimmed = word.trim();
                            if trimmed.contains(':') && !trimmed.contains('/') && !trimmed.contains('\\') && !trimmed.starts_with("http") && trimmed.len() > 3 && trimmed.len() < 60 {
                                items.push(trimmed.to_string());
                            }
                        }
                    }
                }
                // Parse JS / TXT files
                else if file_name.ends_with(".js") || file_name.ends_with(".txt") {
                    if let Ok(content) = fs::read_to_string(&p) {
                        for word in content.split(|c: char| c.is_whitespace() || c == '"' || c == '\'' || c == '`' || c == '(' || c == ')' || c == '[' || c == ']' || c == ',' || c == ';') {
                            let trimmed = word.trim();
                            if trimmed.contains(':') && !trimmed.contains('/') && !trimmed.contains('\\') && !trimmed.starts_with("http") && trimmed.len() > 3 && trimmed.len() < 60 {
                                items.push(trimmed.to_string());
                            }
                        }
                    }
                }
            }
        }
    }
}

fn extract_items_from_json(json: &serde_json::Value, items: &mut Vec<String>) {
    match json {
        serde_json::Value::Array(arr) => {
            for val in arr {
                if let Some(s) = val.as_str() {
                    if s.contains(':') {
                        items.push(s.to_string());
                    }
                } else if val.is_object() {
                    extract_items_from_json(val, items);
                }
            }
        },
        serde_json::Value::Object(map) => {
            if let Some(items_val) = map.get("items").or_else(|| map.get("values")).or_else(|| map.get("entries")) {
                extract_items_from_json(items_val, items);
            } else {
                for (k, v) in map {
                    if k.contains(':') {
                        items.push(k.clone());
                    }
                    if let Some(s) = v.as_str() {
                        if s.contains(':') {
                            items.push(s.to_string());
                        }
                    }
                }
            }
        },
        serde_json::Value::String(s) => {
            if s.contains(':') {
                items.push(s.clone());
            }
        },
        _ => {}
    }
}

fn scan_directory_for_mechanics(dir: &Path, mechanics: &mut Vec<String>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.flatten() {
            let p = entry.path();
            if p.is_dir() {
                scan_directory_for_mechanics(&p, mechanics);
            } else if p.is_file() && p.extension().map_or(false, |e| e == "js") {
                if let Ok(content) = fs::read_to_string(&p) {
                    for line in content.lines() {
                        let trimmed = line.trim();
                        // 1. event.recipes.<mod>.<mechanic>
                        if let Some(idx) = trimmed.find("event.recipes.") {
                            let after = &trimmed[idx + 14..];
                            let token: String = after.chars().take_while(|c| c.is_alphanumeric() || *c == '.' || *c == '_').collect();
                            let parts: Vec<&str> = token.split('.').collect();
                            if parts.len() >= 2 {
                                let mod_id = parts[0];
                                let mech = parts[1];
                                if !mod_id.is_empty() && !mech.is_empty() {
                                    mechanics.push(format!("{}:{}", mod_id, mech));
                                }
                            }
                        }
                        // 2. "type": "mod:mechanic"
                        if trimmed.contains("\"type\":") || trimmed.contains("'type':") || trimmed.contains("type:") {
                            if let Some(colon) = trimmed.find(':') {
                                let val = trimmed[colon + 1..].trim().trim_matches(|c| c == '"' || c == '\'' || c == ',' || c == '`');
                                if val.contains(':') && !val.contains('/') && !val.contains('\\') && !val.starts_with("http") && val.len() < 40 {
                                    mechanics.push(val.to_string());
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}


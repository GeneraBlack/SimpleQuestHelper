#[tauri::command]
pub fn setup_autosync(app_handle: AppHandle, export_path: String) -> Result<String, String> {
    let path = Path::new(&export_path);
    if !path.exists() {
        return Err(format!("Path does not exist: {}", export_path));
    }

    let kubejs_server = path.join("kubejs").join("server_scripts");
    fs::create_dir_all(&kubejs_server).map_err(|e| e.to_string())?;

    let sync_script = r#"// SimpleQuestHelper Auto-Sync Script for Minecraft 1.21.1+
// Automatically generated by SimpleQuestHelper

function sqh_do_export() {
    try {
        let itemList = [];

        // Strategy 1: Minecraft 1.21+ BuiltInRegistries (Java reflection, 100% reliable on 1.21.1 NeoForge/Fabric/Forge)
        try {
            let BuiltInRegistries = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries');
            if (BuiltInRegistries && BuiltInRegistries.ITEM) {
                BuiltInRegistries.ITEM.keySet().forEach(function(k) {
                    if (k) itemList.push(String(k));
                });
            }
        } catch (e1) {}

        // Strategy 2: KubeJS Utils Registry
        if (itemList.length === 0 && typeof Utils !== 'undefined' && Utils.getRegistry) {
            try {
                let reg = Utils.getRegistry('minecraft:item') || Utils.getRegistry('item');
                if (reg) {
                    reg.keySet().forEach(function(k) {
                        if (k) itemList.push(String(k));
                    });
                }
            } catch (e2) {}
        }

        // Strategy 3: Item.getList()
        if (itemList.length === 0 && typeof Item !== 'undefined' && Item.getList) {
            try {
                let all = Item.getList();
                for (let i = 0; i < all.length; i++) {
                    let it = all[i];
                    if (it && it.getId) itemList.push(String(it.getId()));
                }
            } catch (e3) {}
        }

        if (itemList.length > 0) {
            // Deduplicate items
            let uniqueItems = Array.from(new Set(itemList));
            JsonIO.write('kubejs/exported/sqh_items.json', { items: uniqueItems });
            console.info('[SimpleQuestHelper] Exported ' + uniqueItems.length + ' items to kubejs/exported/sqh_items.json');
        }
    } catch (err) {
        console.error('[SimpleQuestHelper] Auto-Sync error: ' + err);
    }
}

// Trigger on World Load & on /reload
ServerEvents.loaded(event => {
    sqh_do_export();
});

ServerEvents.recipes(event => {
    sqh_do_export();
});
"#;
    
    fs::write(kubejs_server.join("sqh_autosync.js"), sync_script).map_err(|e| e.to_string())?;

    // Setup watcher in a background thread
    let watch_path = path.join("kubejs").join("exported");
    fs::create_dir_all(&watch_path).ok(); // Ensure it exists before watching

    std::thread::spawn(move || {
        let mut watcher = match notify::recommended_watcher(move |res: notify::Result<Event>| {
            match res {
                Ok(event) => {
                    if event.kind.is_modify() || event.kind.is_create() {
                        let _ = app_handle.emit("sqh-sync-updated", ());
                    }
                },
                Err(e) => println!("Watch error: {:?}", e),
            }
        }) {
            Ok(w) => w,
            Err(e) => {
                println!("Watcher init error: {:?}", e);
                return;
            }
        };

        if let Err(e) = watcher.watch(&watch_path, RecursiveMode::Recursive) {
            println!("Watch path error: {:?}", e);
        }
        
        loop {
            std::thread::sleep(std::time::Duration::from_secs(60));
        }
    });

    Ok("Auto-Sync script created and folder watcher started successfully!".to_string())
}

#[tauri::command]
pub fn import_modpack_project(export_path: String) -> Result<ModpackData, String> {
    crate::logger::log_info(&format!("Starting full modpack import from: {}", export_path));
    let (data, num_chapters, num_quests) = import_from_instance(&export_path)?;
    crate::logger::log_info(&format!("Modpack import finished: {} chapters, {} quests, {} items, {} recipes", 
        num_chapters, num_quests, data.items.len(), data.recipes.len()));
    Ok(data)
}

